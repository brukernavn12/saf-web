Velkommen:
Nå kan du bli med på innhøstingen i hjertet av Sør-Frankrikes vinlandskap.
Languedoc er Frankrikes største vinregion målt i volum – hver tredje flaske fransk vin kommer herfra. Appellasjonene (AOP) er viktige for å forstå vinene. Særlig innenfor appellasjonene har kvaliteten økt betydelig de siste 30 årene, med større fokus på terroir, lavere avkastning og mer presis vinmaking.
Vi oppholder oss blant annet i Minervois, Minervois-La Livinière og Limoux, og samarbeider med utvalgte produsenter – blant annet Domaine de la Senche og Famille Antech.

Vinregionen:
Minervois ligger mellom Middelhavet og fjellkjeden Montagne Noire, med bølgende og variert landskap. Her dominerer Syrah, Grenache og Carignan. Også Mourvèdre, Vermentino og Viognier dyrkes. Vinene er ofte solmodne og konsentrerte, med struktur og friskhet fra kjølende vinder fra fjellene.
La Livinière var den første cru-klassifiserte landsbyen i Languedoc (AOC Minervois-La Livinière, 1999). Karrig og steinete jordsmonn gir lav avkastning og høy konsentrasjon – kraftige, men elegante viner med stort lagringspotensial.
Limoux har kjøligere påvirkning fra Pyreneene, høyere syre og mer friskhet enn de kraftigere vinene fra Minervois. Her ble verdens første dokumenterte musserende vin laget – méthode ancestrale. Famille Antech, familieeid siden 1800-tallet, lager blant de mest raffinerte Crémant de Limoux på markedet i dag.

Overnatting:
Vi bor midt i Minervois. For kartreferanse kan du søke på Olonzac. Romtype fordeles etter ønske så langt kapasiteten tillater – enkeltrom, dobbeltrom, eller flere romtyper for små grupper.
Alle rom har god standard, med hyggelige fellesområder, uteplass, basseng og wifi. Dette er ekte fransk landsbyliv – baker, små kafeer, markeder og vinmarker rett utenfor døren.

Selve plukkingen:
Plukkingen foregår fra ca. kl. 08 til ca. 12 på ukedager. På gården starter dagen ofte med kaffe, croissant og rolig stemning før vi går ut i vinmarken. Der jobber vi noen gode morgentimer, før vi spiser lunsj – sosialt, med god tid til samtale og spørsmål.
Underveis får du muligheten til å bli med inn i vinkjelleren og se hva som skjer med druene etter innhøstingen. For hvitvinsdruer skjer pressing ofte morgenen etter plukking; druene lagres kjølig over natten slik at temperaturen er lavere ved pressing, noe som bidrar til å bevare friskhet og aromatisk presisjon.
Avstanden til gårdene varierer fra ca. 10 minutter til opptil en time (Limoux). Praktisk gjennomføring og felles avreise avtales under oppholdet.

Rammer og forutsetninger:
Vinplukking er sosial og givende, men kan også være fysisk krevende – man bøyer seg mye. Du deltar i det tempoet og omfanget som passer deg, og pauser tas med hensyn til arbeidet rundt deg.
Du betaler for tilrettelegging, tilgang til produsenter, faglig innhold, overnatting og gjennomføring – ikke selve plukkearbeidet.
Innhøstingen styres av modning og værforhold – druene bestemmer. Vi kan ikke garantere eksakt tidspunkt. Dersom plukketidspunkt endres, avsluttes eller utsettes, planlegger vi alternative vinrelaterte aktiviteter.
Samarbeidet med produsentene er uavhengig – vi mottar ikke betaling eller provisjon for besøk eller deltakelse.

Reisen hit:
Du organiserer selv reisen til Olonzac-området. Fra Norge anbefaler vi fly til Toulouse, Montpellier eller Barcelona. Videre kan du leie bil, ta tog eller avtale henting fra flyplass eller togstasjon. Vi hjelper gjerne med praktiske råd.

Pakkeliste:
Klær som tåler å bli litt skitne. Sko med god såle – joggesko eller lette tursko. Solhatt eller caps, solkrem, og hansker dersom du ønsker.
Temperaturen varierer, men det er ofte shorts-vær. Morgener kan likevel være kjølige – ta gjerne med en lett jakke eller genser.

Resten av dagen:
Utenom plukkingen er det tid til avslapping, bading, lesing, utflukter, vinsmaking eller markedsbesøk. Vi foreslår gjerne små opplevelser underveis. Det legges til rette for felles middager, men det er ingen forpliktelse.

Trygghet:
Normal førlighet anbefales for å delta. Vi anbefaler reise- og avbestillingsforsikring – innhøstingen styres av vær og modning, og programmet tilpasses dette.
I nærområdet finnes apotek og legekontor. Nærmeste sykehus ligger ca. 30 minutter unna. Gi beskjed på forhånd ved allergier eller helsebehov.
