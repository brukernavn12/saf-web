Welcome:
Join us for the harvest in the heart of southern France's wine country.
Languedoc is France's largest wine region by volume – one in three French bottles comes from here. The appellations (AOP) matter for understanding the wines. Quality has risen sharply over the past 30 years, with greater focus on terroir, lower yields and more precise winemaking.
We stay mainly in Minervois, Minervois-La Livinière and Limoux, working with selected producers including Domaine de la Senche and Famille Antech.

The wine region:
Minervois lies between the Mediterranean and the Montagne Noire, with rolling, varied landscape. Syrah, Grenache and Carignan dominate; Mourvèdre, Vermentino and Viognier are also grown. The wines are often sun-ripe and concentrated, with structure and freshness from cooling mountain winds.
La Livinière was Languedoc's first cru-classified village (AOC Minervois-La Livinière, 1999). Stony, rugged soils give low yields and high concentration – powerful yet elegant wines with ageing potential.
Limoux is influenced by cooler air from the Pyrenees, with higher acidity and more freshness than the fuller Minervois wines. The world's first documented sparkling wine was made here – méthode ancestrale. Famille Antech, family-owned since the 1800s, produces some of the finest Crémant de Limoux on the market today.

Accommodation:
We stay in the heart of Minervois. Search for Olonzac on a map for reference. Room types are allocated by preference where capacity allows – single, double, or several rooms for small groups.
All rooms are comfortable, with shared areas, outdoor space, pool and wifi. Real French village life – bakery, cafés, markets and vineyards on the doorstep.

The harvest:
Picking runs from around 8 a.m. to noon on weekdays. On the estate the day often starts with coffee, croissant and a calm moment before we head into the vines. After a good few hours we share lunch – social, with time for conversation and questions.
Along the way you can visit the cellar and see what happens to the grapes after harvest. For white grapes, pressing often takes place the morning after picking; grapes are kept cool overnight so pressing at lower temperature preserves freshness and aromatic precision.
Travel to estates varies from about 10 minutes to up to an hour (Limoux). Practical arrangements and shared departures are agreed during your stay.

Terms and expectations:
Grape picking is sociable and rewarding, but can be physically demanding – you bend a lot. You take part at a pace and level that suits you; breaks are taken with respect for the work around you.
You pay for organisation, access to producers, expert content, accommodation and hosting – not for the picking itself.
The harvest follows ripeness and weather – the grapes decide. We cannot guarantee exact timing. If picking is moved, finished early or postponed, we plan alternative wine-related activities.
Our work with producers is independent – we receive no payment or commission for visits or participation.

Getting here:
You arrange your own travel to the Olonzac area. From Norway we recommend flying to Toulouse, Montpellier or Barcelona. From there you can hire a car, take the train or arrange pick-up from the airport or station. We are happy to advise on practical details.

What to bring:
Clothes that can get dirty. Shoes with good grip – trainers or light hiking shoes. Sun hat or cap, sunscreen, and gloves if you wish.
Temperatures vary, but shorts weather is common. Mornings can be cool – bring a light jacket or sweater.

The rest of the day:
Outside picking there is time to relax, swim, read, take excursions, taste wine or visit markets. We may suggest small experiences along the way. Group dinners can be arranged, with no obligation.

Safety:
Normal mobility is recommended. We advise travel and cancellation insurance – the harvest follows weather and ripeness, and the programme adapts accordingly.
Pharmacy and doctor's surgery are nearby; the nearest hospital is about 30 minutes away. Please tell us in advance about allergies or health needs.
